/**
 * Generates API reference docs from the route registry, so the docs can never drift from the code:
 *   docs/openapi.json, docs/API.md, docs/PERMISSIONS.md
 * Usage: npm run docs:generate   (needs a valid .env, but does not connect to the database)
 */
import fs from 'node:fs';
import path from 'node:path';
import { z, type ZodType } from 'zod';
import { buildOpenApi } from '../src/docs/openapi';
import { allRoutes } from '../src/routes';
import type { RouteMeta } from '../src/utils/route';

type Js = { type?: string | string[]; properties?: Record<string, Js>; required?: string[]; enum?: unknown[]; format?: string; minimum?: number; maximum?: number; minLength?: number; maxLength?: number; minItems?: number; maxItems?: number; pattern?: string; items?: Js; anyOf?: Js[]; oneOf?: Js[]; default?: unknown };

const ROLES = ['CHIEF_EDITOR_ADMIN', 'EDITOR', 'REVIEWER', 'AUTHOR', 'PRODUCTION'] as const;
const ROLE_SHORT: Record<string, string> = { CHIEF_EDITOR_ADMIN: 'Admin', EDITOR: 'Editor', REVIEWER: 'Reviewer', AUTHOR: 'Author', PRODUCTION: 'Prod' };

function js(schema: ZodType): Js {
  try {
    return z.toJSONSchema(schema, { io: 'input', unrepresentable: 'any', target: 'draft-7' }) as Js;
  } catch {
    return {};
  }
}

function typeOf(s: Js): string {
  if (s.enum) return s.enum.map((e) => `\`${String(e)}\``).join(' \\| ');
  const alt = s.anyOf ?? s.oneOf;
  if (alt) return alt.map(typeOf).filter((v, i, a) => a.indexOf(v) === i).join(' \\| ');
  if (s.type === 'array') return `array<${s.items ? typeOf(s.items) : 'any'}>`;
  const t = Array.isArray(s.type) ? s.type.join('|') : (s.type ?? 'any');
  return s.format ? `${t} (${s.format})` : t;
}

function constraints(s: Js): string {
  const c: string[] = [];
  if (s.minLength !== undefined) c.push(`min length ${s.minLength}`);
  if (s.maxLength !== undefined) c.push(`max length ${s.maxLength}`);
  if (s.minimum !== undefined) c.push(`min ${s.minimum}`);
  if (s.maximum !== undefined) c.push(`max ${s.maximum}`);
  if (s.minItems !== undefined) c.push(`min items ${s.minItems}`);
  if (s.maxItems !== undefined) c.push(`max items ${s.maxItems}`);
  if (s.pattern) c.push(`pattern \`${s.pattern.replace(/\|/g, '\\|')}\``);
  if (s.default !== undefined) c.push(`default \`${JSON.stringify(s.default)}\``);
  return c.join(', ');
}

function fieldTable(title: string, schema: ZodType | undefined, extraFiles?: RouteMeta['upload']): string {
  const rows: string[] = [];
  if (schema) {
    const s = js(schema);
    for (const [name, p] of Object.entries(s.properties ?? {})) {
      rows.push(`| \`${name}\` | ${typeOf(p)} | ${(s.required ?? []).includes(name) ? 'yes' : 'no'} | ${constraints(p)} |`);
    }
  }
  for (const f of extraFiles?.fields ?? []) rows.push(`| \`${f.name}\` | file (${f.kind}) | ${f.required ? 'yes' : 'no'} | content-sniffed; max upload size applies |`);
  if (!rows.length) return '';
  return `**${title}**\n\n| Field | Type | Required | Validation |\n|---|---|---|---|\n${rows.join('\n')}\n\n`;
}

const accessText = (m: RouteMeta) => (m.access === 'public' ? 'Public' : m.access === 'any' ? 'Any authenticated role' : m.access.join(', '));

function buildApiMd(): string {
  const byTag = new Map<string, RouteMeta[]>();
  for (const { meta } of allRoutes) byTag.set(meta.tag, [...(byTag.get(meta.tag) ?? []), meta]);

  let md = `# API reference\n\n> Generated by \`npm run docs:generate\` from the route registry — do not edit by hand. Interactive docs: \`/api/docs\` (when \`SWAGGER_ENABLED=true\`), machine-readable: \`docs/openapi.json\`.\n\n`;
  md += `Base path: \`/api/v1\`. Authenticated calls send \`Authorization: Bearer <accessToken>\`.\n\n`;
  md += `## Response envelope\n\n\`\`\`json\n{ "success": true, "message": "…", "data": {}, "meta": null }\n\`\`\`\n\nList endpoints return \`data: []\` and \`meta: { page, pageSize, total, totalPages }\`.\n\n`;
  md += `Errors:\n\n\`\`\`json\n{ "success": false, "message": "Validation failed", "code": "VALIDATION_ERROR", "errors": [{ "field": "email", "message": "Please enter a valid email address" }], "requestId": "…" }\n\`\`\`\n\n`;
  md += `| Status | Meaning |\n|---|---|\n| 200 / 201 / 202 | Success / created / accepted |\n| 400 | Validation failed (\`errors[]\` has field-level details) |\n| 401 | Not authenticated, bad credentials or invalid token |\n| 403 | Authenticated but role not permitted |\n| 404 | Not found (also used for resources the caller may not know exist) |\n| 409 | Conflict or invalid workflow transition (\`INVALID_STATE_TRANSITION\`) |\n| 413 | Upload too large |\n| 422 | Semantically invalid (business rule) |\n| 429 | Rate limit exceeded |\n| 500 / 503 | Server error / dependency or provider unavailable |\n\n`;

  for (const [tag, metas] of byTag) {
    md += `## ${tag}\n\n`;
    for (const m of metas) {
      md += `### \`${m.method.toUpperCase()} /api/v1${m.path}\`\n\n${m.summary}\n\n`;
      if (m.description) md += `${m.description}\n\n`;
      md += `- **Access:** ${accessText(m)}\n`;
      if (m.limiter) md += `- **Rate limit:** \`${m.limiter}\` (configurable in \`.env\`)\n`;
      md += `- **Success:** ${m.status}\n`;
      const errs = new Set<number>([...m.errors, 500, ...(m.access === 'public' ? [] : [401, 403]), ...(m.body || m.query || m.params ? [400] : [])]);
      if (m.limiter) errs.add(429);
      md += `- **Errors:** ${[...errs].sort().join(', ')}\n\n`;
      md += fieldTable('Path parameters', m.params);
      md += fieldTable('Query parameters', m.query);
      md += fieldTable(m.upload ? 'Form fields' : 'Request body', m.body, m.upload);
    }
  }
  return md;
}

function buildPermissionsMd(): string {
  let md = `# Role / permission matrix\n\n> Generated from the route registry. ✔ = allowed. Every check is enforced server-side by middleware; row-level rules (ownership, assignment, editor scope) are applied additionally in the services.\n\n`;
  md += `| Endpoint | Public | ${ROLES.map((r) => ROLE_SHORT[r]).join(' | ')} |\n|---|---|${ROLES.map(() => '---').join('|')}|\n`;
  for (const { meta: m } of allRoutes) {
    const cell = (r: string) => (m.access === 'public' ? '✔' : m.access === 'any' ? '✔' : m.access.includes(r as never) ? '✔' : '');
    md += `| \`${m.method.toUpperCase()} ${m.path}\` | ${m.access === 'public' ? '✔' : ''} | ${ROLES.map(cell).join(' | ')} |\n`;
  }
  md += `\n## Row-level rules\n\n`;
  md += [
    '- **Author**: only their own articles, proofs, payment records and notifications. Never sees reviewer identities, assignments, internal notes, plagiarism data; sees reviewer comments only after a final decision and only those the Editor approved.',
    '- **Reviewer**: only their own assignments; the manuscript view contains no author names/emails/affiliations/title page; manuscript downloads use a neutral filename and have document metadata scrubbed; submitted reviews are locked (also enforced by database triggers).',
    '- **Editor**: articles assigned to them plus unassigned ones. Sees author and reviewer identities.',
    '- **Chief Editor / Admin**: all articles, user and role management, configuration, audit logs, editor assignment.',
    '- **Production**: only accepted articles (Accepted – Production Pending onwards); no reviews, editorial decisions, plagiarism or APC data.',
    '- **Public**: published articles only (metadata, HTML, PDF).',
  ].join('\n');
  return md + '\n';
}

const out = path.resolve(__dirname, '..', 'docs');
fs.mkdirSync(out, { recursive: true });
fs.writeFileSync(path.join(out, 'openapi.json'), JSON.stringify(buildOpenApi(allRoutes), null, 2));
fs.writeFileSync(path.join(out, 'API.md'), buildApiMd());
fs.writeFileSync(path.join(out, 'PERMISSIONS.md'), buildPermissionsMd());
console.log(`Generated docs for ${allRoutes.length} endpoints in ${out}`);
process.exit(0);
